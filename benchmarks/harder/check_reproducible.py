"""Check that the frozen harder task sets are reproduced byte for byte.

Copies the generators into a scratch directory, runs make_tasks.py and make_tasks_v2.py there, and
compares each output with the committed file and with the sha256 that run.mjs pins. The source tree is
never written. Standard library only. Run from anywhere:

    python3 -I benchmarks/harder/check_reproducible.py
"""

from __future__ import annotations

import hashlib
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUTPUTS = {"make_tasks.py": "tasks-v1.json", "make_tasks_v2.py": "tasks-v2.json"}


def pinned_hashes() -> dict[str, str]:
    """Return the sha256 that run.mjs pins for each task file."""
    source = (HERE / "run.mjs").read_text(encoding="utf-8")
    v1 = re.search(r"export const TASKS_SHA256 = '([0-9a-f]{64})';", source)
    v2 = re.search(r"file: 'tasks-v2\.json', sha256: '([0-9a-f]{64})'", source)
    if not v1 or not v2:
        raise SystemExit("run.mjs no longer pins the task hashes in the expected form")
    return {"tasks-v1.json": v1.group(1), "tasks-v2.json": v2.group(1)}


def main() -> int:
    pins = pinned_hashes()
    failures = []
    with tempfile.TemporaryDirectory() as scratch:
        root = Path(scratch) / "harder"
        root.mkdir()
        for script in OUTPUTS:
            shutil.copyfile(HERE / script, root / script)
        shutil.copytree(HERE / "v2" / "generators", root / "v2" / "generators")
        for script, output in OUTPUTS.items():
            subprocess.run(
                [sys.executable, "-I", str(root / script)],
                cwd=root,
                check=True,
                stdout=subprocess.DEVNULL,
                timeout=300,
            )
            produced = (root / output).read_bytes()
            digest = hashlib.sha256(produced).hexdigest()
            if produced != (HERE / output).read_bytes():
                failures.append(f"{output}: regenerated bytes differ from the committed file")
            if digest != pins[output]:
                failures.append(f"{output}: sha256 {digest} does not match the run.mjs pin {pins[output]}")
            print(f"{output} {digest}")
    for failure in failures:
        print(failure, file=sys.stderr)
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
